        function [paths, frameCounts] = preallocateCameraFiles(obj, cameraIndex)
            expected = max(1, round(obj.ExpectedFrames(cameraIndex)));
            segmentFrames = obj.SegmentFrames(cameraIndex);
            segmentCount = max(1, ceil(expected / segmentFrames));
            paths = strings(1, segmentCount);
            frameCounts = zeros(1, segmentCount);
            bytesPerFrame = prod(obj.FrameSizes{cameraIndex}) * 2;
            for segmentIndex = 1:segmentCount
                firstFrame = (segmentIndex - 1) * segmentFrames + 1;
                frameCounts(segmentIndex) = min(segmentFrames, ...
                    expected - firstFrame + 1);
                paths(segmentIndex) = string(fullfile( ...
                    obj.OutputFolders{cameraIndex}, sprintf( ...
                    'Rec_%03d.bin.part', segmentIndex)));
                zoulab.BufferedBinRecorder.setFileLength(paths(segmentIndex), ...
                    frameCounts(segmentIndex) * bytesPerFrame);
            end
        end

        function [paths, frameCounts] = cyclePreallocation(obj, ...
                cameraIndex, preallocation)
            if isempty(preallocation)
                [paths, frameCounts] = obj.preallocateCameraFiles(cameraIndex);
                return;
            end
            cameras = preallocation;
            if isstruct(preallocation) && isfield(preallocation, 'cameras')
                cameras = preallocation.cameras;
            end
            match = find([cameras.camera] == cameraIndex, 1);
            if isempty(match)
                error('ZouLab:BinPreallocationCameraMissing', ...
                    'No preallocation entry exists for Camera %d.', cameraIndex);
            end
            entry = cameras(match);
            paths = string(entry.part_paths);
            frameCounts = double(entry.frame_counts(:).');
            expectedFolder = zoulab.BufferedBinRecorder.normalizedPath( ...
                obj.OutputFolders{cameraIndex});
            bytesPerFrame = prod(obj.FrameSizes{cameraIndex}) * 2;
            if isempty(paths) || numel(paths) ~= numel(frameCounts)
                error('ZouLab:BinPreallocationInvalid', ...
                    'Camera %d preallocation has mismatched paths and counts.', ...
                    cameraIndex);
            end
            for index = 1:numel(paths)
                actualFolder = zoulab.BufferedBinRecorder.normalizedPath( ...
                    fileparts(paths(index)));
                listing = dir(paths(index));
                expectedBytes = frameCounts(index) * bytesPerFrame;
                if actualFolder ~= expectedFolder || ...
                        ~endsWith(paths(index), ".bin.part") || ...
                        isempty(listing) || listing.bytes ~= expectedBytes
                    error('ZouLab:BinPreallocationValidationFailed', ...
                        ['Camera %d segment %d failed folder, suffix, ', ...
                         'existence, or byte-count validation.'], ...
                        cameraIndex, index);
                end
            end
        end

        function waitForWritersReady(obj, timeoutSeconds)
            waitClock = tic;
            while ~all(obj.WriterReady(obj.CameraIndices))
