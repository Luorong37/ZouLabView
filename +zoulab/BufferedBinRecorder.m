                errors = obj.WriterErrors(obj.CameraIndices);
                if any(strlength(errors) > 0)
                    error('ZouLab:BinWriterStartFailed', '%s', ...
                        strjoin(errors(strlength(errors) > 0), ' | '));
                end
                if toc(waitClock) > timeoutSeconds
                    error('ZouLab:BinWriterReadyTimeout', ...
                        'BIN writers were not ready within %.1f seconds.', ...
                        timeoutSeconds);
                end
            end
        end

        function recordMetadataIssues(obj, cameraIndex, issues, blockIndex)
            for issueIndex = 1:numel(issues)
                issue = issues(issueIndex);
                if strcmp(issue.Code, 'METADATA_UNAVAILABLE')
                    level = 'WARNING';
                else
                    level = 'ERROR';
                    obj.MetadataErrorCount(cameraIndex) = ...
                        obj.MetadataErrorCount(cameraIndex) + 1;
                end
                if obj.MetadataDetailLogs(cameraIndex) < ...
                        obj.MetadataDetailLogLimit
                    obj.Logger.log(level, 'RECORD_METADATA_SEQUENCE_ISSUE', ...
                        ['Camera=%d | Block=%d | Code=%s | %s | ', ...
                         'AcquisitionContinues=1'], cameraIndex, blockIndex, ...
                        issue.Code, issue.Message);
                    obj.MetadataDetailLogs(cameraIndex) = ...
                        obj.MetadataDetailLogs(cameraIndex) + 1;
                elseif obj.MetadataDetailLogs(cameraIndex) == ...
                        obj.MetadataDetailLogLimit
                    obj.Logger.log('WARNING', ...
                        'RECORD_METADATA_DETAIL_LOG_LIMIT_REACHED', ...
                        ['Camera=%d | Limit=%d | FurtherDetailsSuppressed=1 | ', ...
                         'FinalAggregateRetained=1'], cameraIndex, ...
                        obj.MetadataDetailLogLimit);
                    obj.MetadataDetailLogs(cameraIndex) = ...
                        obj.MetadataDetailLogs(cameraIndex) + 1;
                end
            end
        end

        function writeBinInfoFiles(obj)
            for cameraIndex = obj.CameraIndices
                files = obj.BinFiles{cameraIndex};
                counts = obj.BinFileFrameCounts{cameraIndex};
                if numel(files) ~= numel(counts)
                    error('ZouLab:BinInfoSegmentCountMismatch', ...
                        ['Camera %d has %d BIN files but %d segment frame ', ...
                         'counts.'], cameraIndex, numel(files), numel(counts));
                end
                infoFiles = strings(1, numel(files));
                firstFrame = 1;
                for segmentIndex = 1:numel(files)
                    cameraMetadata = struct();
                    if numel(obj.CameraMetadata) >= cameraIndex && ...
                            ~isempty(obj.CameraMetadata{cameraIndex})
                        cameraMetadata = obj.CameraMetadata{cameraIndex};
                    end
                    value = zoulab.BinInfo.create(files(segmentIndex), ...
                        cameraIndex, segmentIndex, ...
                        obj.FrameSizes{cameraIndex}, counts(segmentIndex), ...
                        obj.ExpectedFPS(cameraIndex), ...
                        obj.RecorderCreatedUtc, cameraMetadata);
                    value.segment_first_record_frame_index = firstFrame;
                    value.segment_last_record_frame_index = ...
                        firstFrame + counts(segmentIndex) - 1;
                    value.integrity = struct( ...
                        'metadata_error_count_acquisition_total', ...
                            obj.MetadataErrorCount(cameraIndex), ...
                        'metadata_unavailable_block_count_acquisition_total', ...
                            obj.MetadataUnavailableBlockCount(cameraIndex), ...
                        'writer_block_order_error_count_acquisition_total', ...
                            obj.WriterBlockOrderErrorCount(cameraIndex));
                    infoFiles(segmentIndex) = ...
                        zoulab.BinInfo.sidecarPath(files(segmentIndex));
                    zoulab.BinInfo.write(infoFiles(segmentIndex), value);
                    cycleText = 'unscoped';
                    if isfield(value, 'storage') && ...
                            ~isempty(value.storage.cycle_index)
                        cycleText = sprintf('%d', ...
                            value.storage.cycle_index);
                    end
                    obj.Logger.log('SUCCESS', 'BIN_INFO_SAVED', ...
                        ['Cycle=%s | Camera=%d | Segment=%d | Frames=%d | ', ...
                         'Bin=%s | Info=%s | OneInfoPerBin=1 | ', ...
                         'FrameTimestampsStored=0'], cycleText, cameraIndex, ...
                        segmentIndex, counts(segmentIndex), ...
                        files(segmentIndex), infoFiles(segmentIndex));
                    firstFrame = firstFrame + counts(segmentIndex);
                end
                obj.BinInfoFiles{cameraIndex} = infoFiles;
            end
        end
    end
